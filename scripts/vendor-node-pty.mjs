// Syncs the minimal node-pty runtime into vendor/node-pty:
//   lib/*.js      (runtime only, no tests / sourcemaps)
//   prebuilds/**  (all bundled platforms, no .pdb debug symbols)
//   LICENSE       (upstream MIT)
//
// vendor/node-pty/licenses/ holds third-party license texts that upstream does
// not ship in the npm tarball (winpty / conpty) and is preserved as-is.
// Regenerate after bumping the node-pty devDependency:
//   npm install && node scripts/vendor-node-pty.mjs
import fs from 'node:fs'
import path from 'node:path'

const root = path.join(import.meta.dirname, '..')
const sourceDir = path.join(root, 'node_modules', 'node-pty')
const vendorDir = path.join(root, 'vendor', 'node-pty')

if (!fs.existsSync(path.join(sourceDir, 'package.json'))) {
  console.error('node_modules/node-pty not found. Run `npm install` first (node-pty is a devDependency used as the sync source).')
  process.exit(1)
}

const { version } = JSON.parse(fs.readFileSync(path.join(sourceDir, 'package.json'), 'utf8'))
const prebuildsDir = path.join(sourceDir, 'prebuilds')
const platforms = fs.readdirSync(prebuildsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && /^(?:win32|darwin|linux|freebsd)-.+$/.test(entry.name))
  .map((entry) => entry.name)
  .sort()

if (platforms.length === 0) {
  console.error(`No prebuilt platforms found under ${prebuildsDir}.`)
  process.exit(1)
}

function copyTree(from, to, keep) {
  let files = 0
  let bytes = 0
  fs.mkdirSync(to, { recursive: true })
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    if (!keep(entry)) continue
    const source = path.join(from, entry.name)
    const target = path.join(to, entry.name)
    if (entry.isDirectory()) {
      const nested = copyTree(source, target, keep)
      files += nested.files
      bytes += nested.bytes
    } else {
      fs.copyFileSync(source, target)
      files += 1
      bytes += fs.statSync(source).size
    }
  }
  return { files, bytes }
}

for (const dir of ['lib', 'prebuilds']) {
  fs.rmSync(path.join(vendorDir, dir), { recursive: true, force: true })
}

const lib = copyTree(path.join(sourceDir, 'lib'), path.join(vendorDir, 'lib'), (entry) =>
  !entry.name.endsWith('.test.js') && !entry.name.endsWith('.map'))
const prebuilds = copyTree(prebuildsDir, path.join(vendorDir, 'prebuilds'), (entry) =>
  !entry.name.endsWith('.pdb'))

// On macOS node-pty posix_spawns the spawn-helper binary directly; it must keep
// the executable bit. Best-effort (a no-op for exec bits when run on Windows,
// where the runtime self-heal in terminal-manager covers npm-installed copies).
for (const platform of platforms) {
  if (!platform.startsWith('darwin-')) continue
  const helper = path.join(vendorDir, 'prebuilds', platform, 'spawn-helper')
  if (fs.existsSync(helper)) {
    try {
      fs.chmodSync(helper, 0o755)
    } catch { /* best-effort */ }
  }
}
fs.copyFileSync(path.join(sourceDir, 'LICENSE'), path.join(vendorDir, 'LICENSE'))

// The repo package.json sets "type": "module" while node-pty's lib is CommonJS;
// this marker restores CJS resolution for everything under vendor/node-pty.
// It travels as a plain file inside our npm tarball and declares no dependency.
fs.writeFileSync(path.join(vendorDir, 'package.json'), JSON.stringify({
  type: 'commonjs',
  private: true,
  description: 'Vendored node-pty runtime, see README.md. Generated by scripts/vendor-node-pty.mjs.',
}, null, 2) + '\n')

fs.writeFileSync(path.join(vendorDir, 'VENDOR.json'), JSON.stringify({
  source: 'node-pty',
  version,
  platforms,
  generatedAt: new Date().toISOString(),
}, null, 2) + '\n')

const mb = (bytes) => (bytes / 1048576).toFixed(2) + ' MB'
console.log(`Vendored node-pty@${version}: lib ${lib.files} files (${mb(lib.bytes)}), ` +
  `prebuilds ${platforms.join(', ')} (${prebuilds.files} files, ${mb(prebuilds.bytes)}).`)
